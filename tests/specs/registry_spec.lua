local H = require("tests.helpers.addon")

-- 1% of the Stormwind map is 17.375 yd on the second axis (x) and 11.583 yd on the first axis (y).
local YD_PER_X, YD_PER_Y = 17.375, 11.5834

describe("Registry", function()
  describe("adding waypoints", function()
    local ctx = H.use({ boot = true })

    it("returns increasing integer uids", function()
      local a = ctx.ns:AddWaypoint(1453, 50, 50)
      local b = ctx.ns:AddWaypoint(1453, 51, 51)
      expect(a).toBe(1)
      expect(b).toBe(2)
    end)

    it("returns nil for bad arguments instead of raising", function()
      local ns = ctx.ns
      expect(ns:AddWaypoint(nil, 50, 50)).toBeNil()
      expect(ns:AddWaypoint("1453", 50, 50)).toBeNil()
      expect(ns:AddWaypoint(1453, "50", 50)).toBeNil()
      expect(ns:AddWaypoint(1453, 101, 50)).toBeNil()
      expect(ns:AddWaypoint(1453, 50, -1)).toBeNil()
      expect(ns:AddWaypoint(99999, 50, 50)).toBeNil()
    end)

    it("stores defaults and options on the waypoint", function()
      local uid = ctx.ns:AddWaypoint(1453, 50, 50, { title = "Anvil", icon = "kill", arrival_distance = 9, minimap = false })
      local wp = ctx.ns:GetWaypoint(uid)
      expect(wp.title).toBe("Anvil")
      expect(wp.icon).toBe("kill")
      expect(wp.radius).toBe(9)
      expect(wp.minimap).toBe(false)
      expect(wp.worldmap).toBe(true)
      expect(wp.compass).toBe(true)
      expect(wp.visible).toBe(true)
    end)

    it("uses the default title, radius and icon when options are missing or invalid", function()
      local wp = ctx.ns:GetWaypoint(ctx.ns:AddWaypoint(1453, 50, 50, { icon = "nonsense", arrival_distance = "x" }))
      expect(wp.title).toBe("Waypoint")
      expect(wp.radius).toBe(5)
      expect(wp.icon).toBe("poi")
    end)

    it("keeps an optional world height, and none when it is missing or not a number", function()
      expect(ctx.ns:GetWaypoint(ctx.ns:AddWaypoint(1453, 50, 50, { z = 39.5 })).z).toBe(39.5)
      expect(ctx.ns:GetWaypoint(ctx.ns:AddWaypoint(1453, 50, 50, {})).z).toBeNil()
      expect(ctx.ns:GetWaypoint(ctx.ns:AddWaypoint(1453, 50, 50, { z = "high" })).z).toBeNil()
    end)

    it("converts the zone coordinate to world yards through the client", function()
      spyOn(ctx.ns.client, "toWorld"):andReturn(10, 20, 0)
      local wp = ctx.ns:GetWaypoint(ctx.ns:AddWaypoint(1453, 50, 50))
      expect(ctx.ns.client.toWorld).toHaveBeenCalledWith(1453, 50, 50)
      expect(wp.first).toBe(10)
      expect(wp.second).toBe(20)
    end)

    it("rejects a waypoint the client cannot convert", function()
      spyOn(ctx.ns.client, "toWorld"):andReturn(nil)
      expect(ctx.ns:AddWaypoint(1453, 50, 50)).toBeNil()
    end)

    it("fires WAYPOINT_ADDED", function()
      local added = createSpy()
      ctx.ns:On("WAYPOINT_ADDED", added)
      local uid = ctx.ns:AddWaypoint(1453, 50, 50)
      expect(added).toHaveBeenCalledWith(ctx.ns:GetWaypoint(uid))
    end)
  end)

  describe("before the addon is ready", function()
    local ctx = H.use({})

    it("refuses waypoints", function()
      expect(ctx.ns:AddWaypoint(1453, 50, 50)).toBeNil()
    end)
  end)

  describe("removing and hiding", function()
    local ctx = H.use({ boot = true })
    local uid

    beforeEach(function() uid = ctx.ns:AddWaypoint(1453, 50, 50) end)

    it("removes a waypoint and fires WAYPOINT_REMOVED", function()
      local removed = createSpy()
      ctx.ns:On("WAYPOINT_REMOVED", removed)
      ctx.ns:RemoveWaypoint(uid)
      expect(ctx.ns:GetWaypoint(uid)).toBeNil()
      expect(removed).toHaveBeenCalledTimes(1)
    end)

    it("ignores a stale uid", function()
      local removed = createSpy()
      ctx.ns:On("WAYPOINT_REMOVED", removed)
      ctx.ns:RemoveWaypoint(999)
      ctx.ns:SetWaypointVisible(999, false)
      expect(removed).never.toHaveBeenCalled()
    end)

    it("clears the focus when the focused waypoint is removed", function()
      ctx.ns:SetFocus(uid)
      ctx.ns:RemoveWaypoint(uid)
      expect(ctx.ns.focus).toBeNil()
    end)

    it("hides and restores a waypoint, firing WAYPOINT_CHANGED only on a change", function()
      local changed = createSpy()
      ctx.ns:On("WAYPOINT_CHANGED", changed)
      ctx.ns:SetWaypointVisible(uid, false)
      ctx.ns:SetWaypointVisible(uid, false)
      expect(ctx.ns:GetWaypoint(uid).visible).toBe(false)
      expect(changed).toHaveBeenCalledTimes(1)
      ctx.ns:SetWaypointVisible(uid, true)
      expect(ctx.ns:GetWaypoint(uid).visible).toBe(true)
      expect(changed).toHaveBeenCalledTimes(2)
    end)

    it("hides and shows every waypoint without removing any", function()
      local other = ctx.ns:AddWaypoint(1453, 40, 40)
      ctx.ns:HideAll()
      expect(ctx.ns:GetWaypoint(uid).visible).toBe(false)
      expect(ctx.ns:GetWaypoint(other).visible).toBe(false)
      ctx.ns:ShowAll()
      expect(ctx.ns:GetWaypoint(uid).visible).toBe(true)
    end)

    it("clears all waypoints", function()
      ctx.ns:AddWaypoint(1453, 40, 40)
      ctx.ns:ClearAllWaypoints()
      expect(next(ctx.ns.waypoints)).toBeNil()
    end)

    it("ignores a focus request for an unknown waypoint", function()
      ctx.ns:SetFocus(999)
      expect(ctx.ns.focus).toBeNil()
    end)
  end)

  describe("geometry", function()
    local ctx = H.use({ boot = true })

    beforeEach(function() ctx.world:placePlayer(1453, 61.99, 70.58, 0) end)

    it("measures distance in yards and puts a western target on the left", function()
      -- 100 yd west of the player: 100 / 17.375 percent smaller x.
      local uid = ctx.ns:AddWaypoint(1453, 61.99 - 100 / YD_PER_X, 70.58)
      ctx.ns:UpdateGeometry()
      local wp = ctx.ns:GetWaypoint(uid)
      expect(wp.dist).toBeCloseTo(100, 1)
      expect(wp.delta).toBeCloseTo(math.pi / 2, 3)
    end)

    it("puts a target to the north straight ahead when facing north", function()
      local uid = ctx.ns:AddWaypoint(1453, 61.99, 70.58 - 50 / YD_PER_Y)
      ctx.ns:UpdateGeometry()
      local wp = ctx.ns:GetWaypoint(uid)
      expect(wp.dist).toBeCloseTo(50, 1)
      expect(wp.delta).toBeCloseTo(0, 3)
    end)

    it("follows the player's facing", function()
      local uid = ctx.ns:AddWaypoint(1453, 61.99 - 100 / YD_PER_X, 70.58)
      ctx.world.player.facing = math.pi / 2   -- turned a quarter left: now facing west
      ctx.ns:UpdateGeometry()
      expect(ctx.ns:GetWaypoint(uid).delta).toBeCloseTo(0, 3)
    end)

    it("leaves delta unset when facing is unknown but still measures distance", function()
      local uid = ctx.ns:AddWaypoint(1453, 61.99, 70.58 - 50 / YD_PER_Y)
      spyOn(ctx.ns.client, "facing"):andReturn(nil)
      ctx.ns:UpdateGeometry()
      expect(ctx.ns:GetWaypoint(uid).dist).toBeCloseTo(50, 1)
      expect(ctx.ns:GetWaypoint(uid).delta).toBeNil()
    end)

    it("clears distance for a waypoint on another continent (instance)", function()
      local uid = ctx.ns:AddWaypoint(1439, 50, 50)
      ctx.ns:UpdateGeometry()
      expect(ctx.ns:GetWaypoint(uid).dist).toBeNil()
      expect(ctx.ns:GetWaypoint(uid).delta).toBeNil()
    end)

    it("clears distance when the player position is unavailable", function()
      local uid = ctx.ns:AddWaypoint(1453, 50, 50)
      ctx.ns:UpdateGeometry()
      expect(ctx.ns:GetWaypoint(uid).dist).toBeTruthy()
      ctx.world.player.noPosition = true
      ctx.ns:UpdateGeometry()
      expect(ctx.ns:GetWaypoint(uid).dist).toBeNil()
    end)

    it("runs on the 30 Hz ticker", function()
      local uid = ctx.ns:AddWaypoint(1453, 50, 50)
      ctx.world:update(0.04)
      expect(ctx.ns:GetWaypoint(uid).dist).toBeTruthy()
    end)
  end)

  describe("arrival", function()
    local ctx = H.use({ boot = true })
    local arrive, uid

    beforeEach(function()
      ctx.world:placePlayer(1453, 61.99, 70.58, 0)
      arrive = createSpy()
      uid = ctx.ns:AddWaypoint(1453, 61.99, 70.58, { arrival_distance = 5, on_arrive = function(...) arrive(...) end })
    end)

    it("calls on_arrive once on entering the radius", function()
      ctx.ns:UpdateGeometry()
      ctx.ns:UpdateGeometry()
      expect(arrive).toHaveBeenCalledTimes(1)
      expect(arrive.calls[1][1]).toBe(uid)
    end)

    it("fires WAYPOINT_ARRIVED", function()
      local arrived = createSpy()
      ctx.ns:On("WAYPOINT_ARRIVED", arrived)
      ctx.ns:UpdateGeometry()
      expect(arrived).toHaveBeenCalledTimes(1)
    end)

    it("does not re-arm until the player is 1.5x the radius away", function()
      ctx.ns:UpdateGeometry()
      -- 6 yd away: outside 5 yd, inside 7.5 yd.
      ctx.world:placePlayer(1453, 61.99 + 6 / YD_PER_X, 70.58)
      ctx.ns:UpdateGeometry()
      ctx.world:placePlayer(1453, 61.99, 70.58)
      ctx.ns:UpdateGeometry()
      expect(arrive).toHaveBeenCalledTimes(1)
    end)

    it("fires again after leaving 1.5x the radius and returning", function()
      ctx.ns:UpdateGeometry()
      ctx.world:placePlayer(1453, 61.99 + 20 / YD_PER_X, 70.58)
      ctx.ns:UpdateGeometry()
      ctx.world:placePlayer(1453, 61.99, 70.58)
      ctx.ns:UpdateGeometry()
      expect(arrive).toHaveBeenCalledTimes(2)
    end)

    it("ignores elevation: arrival uses 2D distance only", function()
      ctx.ns:UpdateGeometry()
      expect(arrive).toHaveBeenCalledTimes(1)
    end)

    it("reports a failing callback without breaking the update", function()
      ctx.ns:AddWaypoint(1453, 61.99, 70.58, { on_arrive = function() error("callback failed") end })
      expect(function() ctx.ns:UpdateGeometry() end).never.toThrow()
      expect(ctx.world.errors[1]).toMatch("callback failed")
    end)

    it("still arrives when hidden", function()
      ctx.ns:SetWaypointVisible(uid, false)
      ctx.ns:UpdateGeometry()
      expect(arrive).toHaveBeenCalledTimes(1)
    end)
  end)

  describe("Sorted", function()
    local ctx = H.use({ boot = true })

    it("orders visible waypoints nearest first and omits hidden ones", function()
      ctx.world:placePlayer(1453, 50, 50, 0)
      local far = ctx.ns:AddWaypoint(1453, 50, 40)
      local near = ctx.ns:AddWaypoint(1453, 50, 48)
      local hidden = ctx.ns:AddWaypoint(1453, 50, 49)
      ctx.ns:SetWaypointVisible(hidden, false)
      ctx.ns:UpdateGeometry()
      local list = ctx.ns:Sorted()
      expect(#list).toBe(2)
      expect(list[1].uid).toBe(near)
      expect(list[2].uid).toBe(far)
    end)

    it("puts waypoints without a distance last", function()
      ctx.world:placePlayer(1453, 50, 50, 0)
      local elsewhere = ctx.ns:AddWaypoint(1439, 50, 50)
      local here = ctx.ns:AddWaypoint(1453, 50, 40)
      ctx.ns:UpdateGeometry()
      local list = ctx.ns:Sorted()
      expect(list[1].uid).toBe(here)
      expect(list[2].uid).toBe(elsewhere)
    end)
  end)
end)
