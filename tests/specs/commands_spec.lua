local H = require("tests.helpers.addon")

describe("Slash commands", function()
  describe("on a ready addon", function()
    local ctx = H.use({ boot = true })

    it("registers /ribbon", function()
      expect(SLASH_RIBBON1).toBe("/ribbon")
      expect(SlashCmdList.RIBBON).toBeTruthy()
    end)

    it("clear hides every waypoint and show restores them", function()
      local uid = ctx.ns:AddWaypoint(1453, 50, 50)
      SlashCmdList.RIBBON("clear")
      expect(ctx.ns:GetWaypoint(uid).visible).toBe(false)
      SlashCmdList.RIBBON("show")
      expect(ctx.ns:GetWaypoint(uid).visible).toBe(true)
    end)

    it("routes commands to the registry", function()
      spyOn(ctx.ns, "HideAll")
      ctx.ns.commands.clear()
      expect(ctx.ns.HideAll).toHaveBeenCalled()
    end)

    it("remove deletes a waypoint by uid", function()
      local uid = ctx.ns:AddWaypoint(1453, 50, 50)
      SlashCmdList.RIBBON("remove " .. uid)
      expect(ctx.ns:GetWaypoint(uid)).toBeNil()
    end)

    it("remove reports an unknown uid", function()
      SlashCmdList.RIBBON("remove 42")
      expect(ctx.world:output()).toContain("no such waypoint")
    end)

    it("list prints visible waypoints", function()
      ctx.ns:AddWaypoint(1453, 50, 50, { title = "Anvil" })
      ctx.ns:UpdateGeometry()
      SlashCmdList.RIBBON("list")
      expect(ctx.world:output()).toContain("Anvil")
    end)

    it("list says so when there are none", function()
      SlashCmdList.RIBBON("list")
      expect(ctx.world:output()).toContain("no visible waypoints")
    end)

    it("debug prints the client position and map", function()
      SlashCmdList.RIBBON("debug")
      expect(ctx.world:output()).toContain("1453")
    end)

    it("prints the command list for an unknown command", function()
      SlashCmdList.RIBBON("frobnicate")
      expect(ctx.world:output()).toContain("commands:")
    end)

    it("is case-insensitive", function()
      local uid = ctx.ns:AddWaypoint(1453, 50, 50)
      SlashCmdList.RIBBON("CLEAR")
      expect(ctx.ns:GetWaypoint(uid).visible).toBe(false)
    end)
  end)

  describe("on a dormant addon", function()
    local ctx = H.use({ world = function(w) w:removeApi("UnitPosition") end })

    it("says it is dormant and names the missing API", function()
      ctx.world:fireEvent("PLAYER_LOGIN")
      SlashCmdList.RIBBON("list")
      expect(ctx.world:output()).toContain("dormant")
      expect(ctx.world:output()).toContain("UnitPosition")
    end)
  end)
end)
